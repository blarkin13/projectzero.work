import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import account from '../workers/projectzero-commercial/worker.mjs';
import dash from '../workers/portfolio-owner/worker.mjs';
const A='https://account.projectzero.work',D='https://dash.projectzero.work';
const token=()=>Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64url');
const hash=async v=>Buffer.from(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(v))).toString('hex');
test('owner Google session handoff, replay prevention, protected dashboard, and revocation',async()=>{
 const sql=new DatabaseSync(':memory:');
 sql.exec(readFileSync('schema/commercial.sql','utf8'));
 sql.exec(readFileSync('schema/migrations/004-owner-dashboard-auth.sql','utf8'));
 const db={prepare(q){const p=sql.prepare(q);return {bind(...a){return {first:async()=>p.get(...a)||null,run:async()=>p.run(...a),all:async()=>({results:p.all(...a)})}}}}};
 const session=token(),now=Math.floor(Date.now()/1000);
 sql.prepare("INSERT INTO users(id,oidc_subject,email) VALUES('u','subject','owner@gmail.com')").run();
 sql.prepare("INSERT INTO sessions(token_hash,user_id,expires_at) VALUES(?,'u',?)").run(await hash(session),now+3600);
 const ae={COMMERCIAL_DB:db,CUSTOMER_ACCESS:'enabled',GOOGLE_LOGIN_MODE:'owner_only',OWNER_EMAIL:'owner@gmail.com',GOOGLE_CLIENT_ID:'test.apps.googleusercontent.com',GOOGLE_CLIENT_SECRET:'synthetic',GOOGLE_OAUTH_STATE_KEY:token(),AUTH_RATE_LIMIT:{limit:async()=>({success:true})}};
 const de={ACCOUNT_AUTH_DB:db,OWNER_EMAIL:'owner@gmail.com'};
 const req=(url,opts={})=>new Request(url,opts);
 const getStatus=cookie=>dash.fetch(req(D+'/api/session-status',{headers:{origin:'https://www.projectzero.work',...(cookie?{cookie}:{})}}),de,{});
 assert.equal((await getStatus()).status,403);
 assert.equal((await dash.fetch(req(D+'/development',{headers:{accept:'text/html'}}),de,{})).headers.get('location'),A+'/auth/dashboard');
 const page=await account.fetch(req(A+'/auth/dashboard',{headers:{cookie:'__Host-pz_session='+session}}),ae);
 assert.equal(page.status,200);const markup=await page.text();const code=markup.match(/name="code" value="([a-zA-Z0-9_-]{43})"/)[1];
 assert.equal(sql.prepare('SELECT token_hash FROM owner_dashboard_codes').get().token_hash,await hash(code));
 const redeem=(origin,c=code)=>dash.fetch(req(D+'/auth/bridge',{method:'POST',headers:{origin,'content-type':'application/x-www-form-urlencoded'},body:new URLSearchParams({code:c})}),de,{});
 assert.equal((await redeem('https://evil.example')).status,403);
 const bridge=await redeem(A);assert.equal(bridge.status,303);
 const cookie=bridge.headers.getSetCookie()[0].split(';')[0];assert.match(cookie,/^__Host-pz_dash=/);assert.equal((await redeem(A)).status,403);
 assert.equal((await getStatus(cookie)).status,204);
 assert.equal((await getStatus('__Host-pz_dash='+token())).status,403);
 assert.equal((await dash.fetch(req(D+'/development',{method:'POST',headers:{cookie,origin:'https://evil.example'}}),de,{})).status,403);
 const help=await dash.fetch(req(D+'/lifecycle?help=1',{headers:{cookie,accept:'text/html'}}),de,{});assert.equal(help.status,200);const helpHtml=await help.text();assert.match(helpHtml,/<footer class="pz-standard-footer"/);assert.match(helpHtml,/href="https:\/\/www\.projectzero\.work\/terms"/);assert.match(helpHtml,/href="https:\/\/guides\.projectzero\.work\/how-to"/);assert.equal((helpHtml.match(/<footer class="pz-standard-footer"/g)||[]).length,1);
 const logout=await dash.fetch(req(D+'/workspace-sign-out',{headers:{cookie}}),de,{});assert.equal(logout.status,303);
 assert.equal((await getStatus(cookie)).status,403);
 assert.equal((await account.fetch(req(A+'/auth/dashboard',{headers:{cookie:'__Host-pz_session='+session}}),ae)).headers.get('location'),'/auth/login');
});
